"""Autonomous DevOps and Deployment Automation Engine for Smart AI Gateway.

Provides infrastructure as code generation and deployment orchestration:
- Dockerfile generation for Python, Node.js, and static web apps.
- Docker Compose multi-service configuration generation.
- CI/CD workflow generator (GitHub Actions).
- Service health monitoring and latency diagnostics.
- Render and cloud deployment inspection.
"""

from __future__ import annotations

import time
from pathlib import Path
from typing import Any, Dict, List, Optional, Tuple
import urllib.request


class DevOpsManager:
    """Manages containerization, CI/CD, and deployment monitoring."""

    def __init__(self, workspace_root: Optional[Path | str] = None):
        self.workspace_root = Path(workspace_root).resolve() if workspace_root else Path.cwd().resolve()

    def generate_dockerfile(
        self,
        project_type: str = "python",
        port: int = 8000,
        entrypoint: Optional[str] = None,
    ) -> str:
        """Generates an optimized Dockerfile for the project type."""
        pt = project_type.lower()
        if pt in ("python", "fastapi", "flask"):
            cmd = entrypoint or "python app.py"
            return f"""# Generated by Smart AI DevOps Engine
FROM python:3.11-slim

WORKDIR /app

# Install system dependencies
RUN apt-get update && apt-get install -y --no-install-recommends \\
    curl \\
    && rm -rf /var/lib/apt/lists/*

# Install python dependencies
COPY requirements.txt .
RUN pip install --no-cache-dir -r requirements.txt

# Copy application source
COPY . .

EXPOSE {port}

CMD [{", ".join(f'"{c}"' for c in cmd.split())}]
"""
        elif pt in ("node", "javascript", "typescript", "express"):
            cmd = entrypoint or "node index.js"
            return f"""# Generated by Smart AI DevOps Engine
FROM node:20-alpine

WORKDIR /app

COPY package*.json ./
RUN npm ci --only=production

COPY . .

EXPOSE {port}

CMD [{", ".join(f'"{c}"' for c in cmd.split())}]
"""
        else:
            return """# Static Web Server
FROM nginx:alpine
COPY . /usr/share/nginx/html
EXPOSE 80
CMD ["nginx", "-g", "daemon off;"]
"""

    def generate_docker_compose(
        self,
        services: Optional[List[Dict[str, Any]]] = None,
    ) -> str:
        """Generates a docker-compose.yml configuration."""
        svc_list = services or [
            {
                "name": "web",
                "build": ".",
                "ports": ["8000:8000"],
                "env_file": [".env"],
            }
        ]

        lines = ["version: '3.8'", "services:"]
        for s in svc_list:
            name = s.get("name", "app")
            lines.append(f"  {name}:")
            lines.append(f"    build: {s.get('build', '.')}")
            if "ports" in s:
                lines.append("    ports:")
                for p in s["ports"]:
                    lines.append(f'      - "{p}"')
            if "environment" in s:
                lines.append("    environment:")
                for k, v in s["environment"].items():
                    lines.append(f"      - {k}={v}")
            lines.append("    restart: unless-stopped")

        return "\n".join(lines) + "\n"

    def generate_github_actions_ci(
        self,
        name: str = "Smart AI CI",
        python_version: str = "3.11",
        run_tests: bool = True,
    ) -> str:
        """Generates GitHub Actions workflow configuration."""
        test_step = (
            """      - name: Run Pytest Suite
        run: |
          pytest -q
"""
            if run_tests
            else ""
        )

        return f"""name: {name}

on:
  push:
    branches: [main, master]
  pull_request:
    branches: [main, master]

jobs:
  build-and-test:
    runs-on: ubuntu-latest
    steps:
      - name: Checkout Code
        uses: actions/checkout@v4

      - name: Set up Python {python_version}
        uses: actions/setup-python@v5
        with:
          python-version: '{python_version}'
          cache: 'pip'

      - name: Install Dependencies
        run: |
          python -m pip install --upgrade pip
          if [ -f requirements.txt ]; then pip install -r requirements.txt; fi
          pip install pytest
{test_step}"""

    def check_health(self, url: str, timeout_seconds: int = 5) -> Tuple[bool, Dict[str, Any]]:
        """Performs HTTP health probe and measures latency."""
        start = time.time()
        try:
            req = urllib.request.Request(url, headers={"User-Agent": "SmartAI-HealthProbe/1.0"})
            with urllib.request.urlopen(req, timeout=timeout_seconds) as resp:
                elapsed = time.time() - start
                status = resp.status
                return (200 <= status < 400), {
                    "url": url,
                    "status_code": status,
                    "latency_ms": round(elapsed * 1000, 2),
                    "is_healthy": 200 <= status < 400,
                }
        except Exception as exc:
            elapsed = time.time() - start
            return False, {
                "url": url,
                "error": str(exc),
                "latency_ms": round(elapsed * 1000, 2),
                "is_healthy": False,
            }


default_devops_manager = DevOpsManager()
